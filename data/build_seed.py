# Generates supabase/seed.sql from data/products.json.
# Retail prices are NOT seeded — they are computed by compute_retail_price()
# once RETAIL_MARKUP_PERCENT is confirmed (see PLACEHOLDERS.md).
import json
import re
from pathlib import Path

root = Path(__file__).parent
products = json.loads((root / "products.json").read_text(encoding="utf-8"))
out = root.parent / "supabase" / "seed.sql"

CATEGORIES = [
    ("solar-panels", "Solar Panels — Tier 1", "Mono and bifacial modules, 350W–715W", 1),
    ("battery-storage", "Battery Storage", "LiFePO4 wall, rack and high-voltage systems", 2),
    ("inverters", "Inverters", "Hybrid, off-grid and grid-tied, 3kW–125kW", 3),
    ("solar-water-heaters", "Solar Water Heaters & Heat Pumps", "Pressurised flat-plate and vacuum-tube systems", 4),
    ("street-lights-cctv", "Solar Street Lights & CCTV", "All-in-one lighting and solar-powered security", 5),
    ("irrigation-pumps", "Irrigation Pumps", "Submersible and surface solar pumping", 6),
    ("water-treatment", "Water Treatment", "Filtration and reverse-osmosis systems", 7),
    ("balance-of-system", "Balance of System", "Protection, distribution, cabling and connectors", 8),
]


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def arr(items):
    return "array[" + ", ".join(q(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


lines = ["-- Generated by data/build_seed.py — do not edit by hand.", ""]

lines.append("insert into categories (id, name, descriptor, sort_order) values")
lines.append(",\n".join(f"  ({q(c[0])}, {q(c[1])}, {q(c[2])}, {c[3]})" for c in CATEGORIES) + ";")
lines.append("")

brands = sorted({p["brand"] for p in products})
lines.append("insert into brands (id, name) values")
lines.append(",\n".join(
    f"  ({q(re.sub(r'[^a-z0-9]+', '-', b.lower()).strip('-'))}, {q(b)})" for b in brands) + ";")
lines.append("")

for p in products:
    brand_id = re.sub(r"[^a-z0-9]+", "-", p["brand"].lower()).strip("-")
    lines.append(
        "insert into products (slug, name, brand, model_code, category, subcategory, "
        "short_description, long_description, specs, key_specs, images, cost_price, cost_per_watt, "
        "module_watts, price_status, source_vat_inclusive, pricing_note, warranty_years, "
        "stock_status, stock_qty, requires_installation, compatible_with, datasheet_url, "
        "is_featured, is_published, source_supplier, source_list_date) values ("
        f"{q(p['slug'])}, {q(p['name'])}, {q(brand_id)}, {q(p['model_code'])}, "
        f"{q(p['category'])}, {q(p['subcategory'])}, {q(p['short_description'])}, "
        f"{q(p['long_description'])}, {q(json.dumps(p['specs']))}::jsonb, {arr(p['key_specs'])}, "
        f"{q(json.dumps(p['images']))}::jsonb, "
        f"{q(p['cost_price'])}, {q(p['cost_per_watt'])}, {q(p['module_watts'])}, "
        f"{q(p['price_status'])}::price_status, {q(p['source_vat_inclusive'])}, "
        f"{q(p['pricing_note'])}, {q(p['warranty_years'])}, "
        f"{q(p['stock_status'])}::stock_status, {q(p['stock_qty'])}, "
        f"{q(p['requires_installation'])}, {arr(p['compatible_with'])}, {q(p['datasheet_url'])}, "
        f"{q(p['is_featured'])}, {q(p['is_published'])}, "
        f"{q(p['source_supplier'])}, {q(p['source_list_date'])});"
    )

out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"seed.sql written: {len(products)} products, {len(brands)} brands, {len(CATEGORIES)} categories")
