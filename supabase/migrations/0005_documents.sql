-- Invoices, receipts and the email audit trail.
--
-- HOW TO RUN THIS
--   Supabase dashboard -> SQL Editor -> New query -> paste this whole file
--   -> Run. It is additive and safe to re-run: every object is created with
--   `if not exists`, so nothing already in the database is touched.
--
-- WHY A SEPARATE TABLE RATHER THAN DERIVING FROM `orders`
--   Two thirds of this company's trade walks through the door. Those customers
--   never place an order, so there is no order row to render a receipt from —
--   the document IS the record. Online orders get a document too, generated
--   from the order, so that both halves of the business are receipted from one
--   place, numbered in one series, and reprint identically years later.
--
--   The document is a SNAPSHOT, deliberately. Prices, names and VAT treatment
--   are copied in at issue and never read back through a join. A receipt is a
--   legal record of what was actually charged on the day; if a product's price
--   changes next month, the reprint must not change with it.

-- ---------------------------------------------------------------------------
-- Types
-- ---------------------------------------------------------------------------
do $$ begin
  create type document_type as enum ('invoice', 'receipt');
exception when duplicate_object then null; end $$;

-- draft   — being written, not yet given to anyone, number not yet burnt
-- issued  — sent or handed over; money still owed
-- paid    — settled in full
-- part_paid — a deposit has been taken, balance outstanding
-- void    — cancelled after issue. Never deleted: the number must stay used.
do $$ begin
  create type document_status as enum ('draft', 'issued', 'part_paid', 'paid', 'void');
exception when duplicate_object then null; end $$;

-- ---------------------------------------------------------------------------
-- Numbering
-- ---------------------------------------------------------------------------
-- Separate series per document type, matching the order-number shape already
-- in use (ORL-2608-00001). A gapless series is not attempted: a draft that is
-- abandoned would leave a hole, and pretending otherwise would be worse than
-- admitting it. Numbers are allocated at ISSUE, not at draft creation, which
-- keeps the holes to genuine mistakes only.
create sequence if not exists invoice_number_seq;
create sequence if not exists receipt_number_seq;

create or replace function next_document_number(p_type text) returns text
language plpgsql volatile as $$
begin
  if p_type = 'invoice' then
    return 'ORL-INV-' || to_char(now(), 'YYMM') || '-' ||
           lpad(nextval('invoice_number_seq')::text, 4, '0');
  elsif p_type = 'receipt' then
    return 'ORL-RCP-' || to_char(now(), 'YYMM') || '-' ||
           lpad(nextval('receipt_number_seq')::text, 4, '0');
  else
    raise exception 'Unknown document type: %', p_type;
  end if;
end $$;

-- ---------------------------------------------------------------------------
-- Documents
-- ---------------------------------------------------------------------------
create table if not exists documents (
  id uuid primary key default gen_random_uuid(),
  doc_type document_type not null,
  -- Null while a draft. Unique once allocated, so two staff issuing at the
  -- same moment cannot land on the same number.
  doc_number text unique,
  status document_status not null default 'draft',

  -- Where it came from. 'order' documents are generated by the system from a
  -- web order; 'walk_in' documents are typed by staff for someone who bought
  -- over the counter. Both render identically — the customer cannot tell, and
  -- should not be able to.
  source text not null default 'walk_in',
  order_id uuid references orders(id) on delete set null,

  -- Guards the public PDF link that goes out over WhatsApp. Not enumerable.
  access_token uuid not null default gen_random_uuid(),

  -- Customer snapshot. Only the name is required: a counter sale often has
  -- nothing else, and refusing to issue a receipt without an email address
  -- would make the till stop working.
  customer_name text not null,
  customer_phone text,
  customer_email text,
  customer_address text,
  kra_pin text,

  -- The tick-box row across the top of the paper form.
  goods_categories text[] not null default '{}',

  -- [{ description, quantity, unitPrice (nullable), amount }]
  -- `amount` is stored rather than computed because the paper form allows a
  -- negotiated line total that is not quantity x unit price — the sample
  -- receipt has exactly that, a 300L heat pump listed at 199,940 and charged
  -- at 180,940. Recomputing would silently overwrite the discount.
  lines jsonb not null default '[]',

  -- exclusive — line amounts are net, VAT is added on top (the paper form)
  -- inclusive — line amounts already contain VAT, which is backed out for the
  --             summary (every price on the website is VAT-inclusive retail)
  -- none      — no VAT line at all
  vat_mode text not null default 'exclusive',
  vat_rate numeric(5,2) not null default 16,

  subtotal numeric(12,2) not null default 0,   -- always net of VAT
  vat_amount numeric(12,2) not null default 0,
  total numeric(12,2) not null default 0,
  amount_paid numeric(12,2) not null default 0,
  balance numeric(12,2) not null default 0,

  payment_method text,                          -- cash | mpesa | bank_transfer | cheque
  mpesa_till text,
  mpesa_code text,
  bank_ref text,

  received_by text,                             -- who took the money, for the signature line
  notes text,
  due_date date,

  issued_at timestamptz,
  last_sent_at timestamptz,
  last_sent_to text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists documents_created_idx on documents (created_at desc);
create index if not exists documents_order_idx on documents (order_id);
create index if not exists documents_status_idx on documents (doc_type, status);
-- Finding "that receipt for the hotel in Kilimani" is the single most common
-- search a counter clerk runs, and they will not remember the number.
create index if not exists documents_customer_idx on documents (lower(customer_name));

create or replace function touch_documents_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;

drop trigger if exists documents_updated_at on documents;
create trigger documents_updated_at
  before update on documents
  for each row execute function touch_documents_updated_at();

-- A number, once issued, is never reused and never cleared. Voiding is the
-- only way to retire a document, and the row stays.
create or replace function protect_issued_document_number()
returns trigger language plpgsql as $$
begin
  if old.doc_number is not null and new.doc_number is distinct from old.doc_number then
    raise exception 'Document number % has been issued and cannot be changed', old.doc_number;
  end if;
  return new;
end $$;

drop trigger if exists documents_number_immutable on documents;
create trigger documents_number_immutable
  before update on documents
  for each row execute function protect_issued_document_number();

-- ---------------------------------------------------------------------------
-- Email audit trail
-- ---------------------------------------------------------------------------
-- Every send attempt, including the failures. When a customer rings to say
-- they never got their receipt, the answer has to be checkable rather than
-- guessed at — and a bounced address is worth knowing about before the same
-- message is sent again.
create table if not exists email_log (
  id uuid primary key default gen_random_uuid(),
  to_address text not null,
  subject text not null,
  template text not null,
  order_id uuid references orders(id) on delete set null,
  document_id uuid references documents(id) on delete set null,
  provider_message_id text,
  status text not null,                         -- sent | failed | skipped
  error text,
  created_at timestamptz not null default now()
);

create index if not exists email_log_created_idx on email_log (created_at desc);
create index if not exists email_log_order_idx on email_log (order_id);

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
-- Both tables hold customer names, phone numbers and what people paid. No anon
-- or authenticated access at all: reads and writes go through the service role
-- from the server, exactly as orders and payments do. RLS on with no policy
-- means the front door is shut. The customer's own copy is reached by the
-- signed access_token through a server route, never by querying the table.
alter table documents enable row level security;
alter table email_log enable row level security;

create policy "staff all documents" on documents for all using (is_staff());
create policy "staff read email_log" on email_log for select using (is_staff());
